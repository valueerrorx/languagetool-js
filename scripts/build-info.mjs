// Writes resources/git.properties (D-023: build metadata of the port; version from the pinned Java build, commit and time from this repository).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// formats a Date as yyyy-MM-dd'T'HH:mm:ssZ with the local offset (Java Properties escaping of ':' is applied by the caller)
function isoLocal(d) {
  const p = (n) => String(n).padStart(2, '0');
  const off = -d.getTimezoneOffset();
  const sign = off < 0 ? '-' : '+';
  const a = Math.abs(off);
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}T${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}${sign}${p(Math.floor(a / 60))}${p(a % 60)}`;
}

export function writeBuildInfo(javaSrc, outDir) {
  const javaProps = readFileSync(path.join(javaSrc, 'languagetool-core/target/classes/git.properties'), 'utf8');
  const version = /^git\.build\.version=(.*)$/m.exec(javaProps)[1];
  let commit = 'unknown';
  try {
    commit = execFileSync('git', ['-C', ROOT, 'rev-parse', '--short=7', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch { /* not a git checkout */ }
  const lines = ['#Generated by scripts/build-info.mjs', `git.build.time=${isoLocal(new Date()).replaceAll(':', '\\:')}`, `git.build.version=${version}`, `git.commit.id.abbrev=${commit}`];
  writeFileSync(path.join(outDir, 'git.properties'), `${lines.join('\n')}\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeBuildInfo(process.env.LTJS_JAVA_SRC ?? path.join(ROOT, 'oracle/java-src'), path.join(ROOT, 'resources'));
}
