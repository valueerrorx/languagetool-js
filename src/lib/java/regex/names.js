let byName = null;

// Java: Character#codePointOf(String) for the supported range; -1 when the name is invalid
export function codePointOfName(name) {
  if (byName === null) {
    byName = new Map();
    for (const row of TABLE.split('\n')) {
      const i = row.indexOf('=');
      byName.set(row.substring(i + 1), parseInt(row.substring(0, i), 16));
    }
  }
  const key = name.trim().toUpperCase();
  const cp = byName.get(key);
  if (cp !== undefined) return cp;
  if (/^[A-Z0-9 -]+$/.test(key) && key.length >= 4) {
    throw new IllegalArgumentException(`java regex translator: character name table covers only U+0020..U+00FF, cannot resolve \\N{${name}}`);
  }
  return -1;
}
