// Ported from DiffsAsMatchesTest (languagetool-core)
import { describe, it, expect } from 'vitest';
import { DiffsAsMatches } from '../../../src/core/tools/DiffsAsMatches.js';
import { abstractCollectionToString } from '../../../src/lib/java/toString.js';

const toStr = (l) => abstractCollectionToString(l);

describe('DiffsAsMatchesTest', () => {
  // Java: DiffsAsMatchesTest#testDiffsAsMatches
  it('testDiffsAsMatches', () => {
    const diffsAsMatches = new DiffsAsMatches();
    const original0 = "This is a \"thing\". This is.";
    const revised0 = "This is a \"thing.\" This is.";
    const matches0 = diffsAsMatches.getPseudoMatches(original0, revised0);
    expect(1).toBe(matches0.length);
    expect(toStr(matches0[0].getReplacements())).toBe("[\"thing.\"]");
    expect(10).toBe(matches0[0].getFromPos());
    expect(18).toBe(matches0[0].getToPos());
    let original = "This are a sentence with too mistakes.";
    let revised = "This is a sentence with two mistakes.";
    let matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(matches.length).toBe(2);
    expect(toStr(matches[0].getReplacements())).toBe("[is]");
    expect(matches[0].getFromPos()).toBe(5);
    expect(matches[0].getToPos()).toBe(8);
    expect(toStr(matches[1].getReplacements())).toBe("[two]");
    expect(matches[1].getFromPos()).toBe(25);
    expect(matches[1].getToPos()).toBe(28);
    original = "I am going to er remove one word.";
    revised = "I am going to remove one word.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[]");
    expect(14).toBe(matches[0].getFromPos());
    expect(17).toBe(matches[0].getToPos());
    original = "And I am going to remove one word.";
    revised = "I am going to remove one word.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[]");
    expect(0).toBe(matches[0].getFromPos());
    expect(4).toBe(matches[0].getToPos());
    original = "I am going to add word.";
    revised = "I am going to add one word.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[add one]");
    expect(14).toBe(matches[0].getFromPos());
    expect(17).toBe(matches[0].getToPos());
    original = "a word at the start.";
    revised = "Add a word at the start.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[Add a]");
    expect(0).toBe(matches[0].getFromPos());
    expect(1).toBe(matches[0].getToPos());
    original = "Add word at position 1.";
    revised = "Add a word at position 1.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[Add a]");
    expect(0).toBe(matches[0].getFromPos());
    expect(3).toBe(matches[0].getToPos());
    original = "Esta serealiza cada semana.";
    revised = "Esta se realiza cada semana.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[se realiza]");
    expect(5).toBe(matches[0].getFromPos());
    expect(14).toBe(matches[0].getToPos());
    original = "Una cosa,una altra.";
    revised = "Una cosa, una altra.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[cosa, ]");
    expect(4).toBe(matches[0].getFromPos());
    expect(9).toBe(matches[0].getToPos());
    original = "Que el año nuevo empezó.";
    revised = "El año nuevo empezó.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[El]");
    expect(0).toBe(matches[0].getFromPos());
    expect(6).toBe(matches[0].getToPos());
    original = "¡Holà ! Estamos aquí.";
    revised = "¡Hola! Estamos aquí.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[¡Hola!]");
    expect(0).toBe(matches[0].getFromPos());
    expect(7).toBe(matches[0].getToPos());
    original = "I truely reserve.";
    revised = "I truly deserve.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[truly deserve]");
    expect(2).toBe(matches[0].getFromPos());
    expect(16).toBe(matches[0].getToPos());
    original = "}Describes how plants are important";
    revised = "It describes how plants are important";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[It describes]");
    expect(0).toBe(matches[0].getFromPos());
    expect(10).toBe(matches[0].getToPos());
    original = "(Calle)Hace falta tener en cuenta una economía estable, un trabajo bueno.";
    revised = "Hace falta tener en cuenta una economía estable, un trabajo bueno.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[]");
    expect(0).toBe(matches[0].getFromPos());
    expect(7).toBe(matches[0].getToPos());
    original = "(Calle)Hace falta tener en cuenta una economía estable, un trabajo bueno.";
    revised = "(Calle) Hace falta tener en cuenta una economía estable, un trabajo bueno.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[Calle) ]");
    expect(1).toBe(matches[0].getFromPos());
    expect(7).toBe(matches[0].getToPos());
    original = "Joan Caprí fou un actor humorista i monologuista català.";
    revised = "Joan Caprí fou un actor, humorista i monologuista català.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[actor,]");
    expect(18).toBe(matches[0].getFromPos());
    expect(23).toBe(matches[0].getToPos());
    original = "Ei he vist el teu amic!";
    revised = "Ei, he vist el teu amic!";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
    expect(toStr(matches[0].getReplacements())).toBe("[Ei,]");
    expect(0).toBe(matches[0].getFromPos());
    expect(2).toBe(matches[0].getToPos());
    original = "Va arribar tard a l'examen, perdent així després tota oportunitat d'aprovar l'assignatura.";
    revised = "Va arribar tard a l'examen i, per això, va perdre tota oportunitat d'aprovar l'assignatura.";
    matches = diffsAsMatches.getPseudoMatches(original, revised);
    expect(1).toBe(matches.length);
  });
});
